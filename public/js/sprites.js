  function svgFromGrid(rows, palette){
    var n = rows.length, w = rows[0].length;
    var out = '<svg viewBox="0 0 '+w+' '+n+'" shape-rendering="crispEdges" xmlns="http://www.w3.org/2000/svg">';
    for(var y=0;y<n;y++){
      var row = rows[y];
      var x=0;
      while(x<row.length){
        var ch = row[x];
        if(ch === '.'){ x++; continue; }
        var run=1;
        while(x+run<row.length && row[x+run]===ch) run++;
        var color = palette[ch];
        if(color) out += '<rect x="'+x+'" y="'+y+'" width="'+run+'" height="1" fill="'+color+'"/>';
        x+=run;
      }
    }
    out += '</svg>';
    return out;
  }

